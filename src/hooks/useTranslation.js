import { useLocation } from "react-router-dom";
import en from "../i18n/en.json";

// Dynamically import de.json when it exists.
// Falls back to English if German translation is not available yet.
let de = null;
try {
  de = (await import("../i18n/de.json")).default;
} catch {
  de = null;
}

/**
 * useTranslation()
 *
 * Returns the translation object for the current language.
 * If the URL starts with /de/, returns German (de.json).
 * Otherwise returns English (en.json).
 *
 * Usage:
 *   const t = useTranslation();
 *   <h1>{t.hero.headline}</h1>
 *
 * When German pages are ready:
 *   1. Drop src/i18n/de.json (generated by n8n + GPT-4)
 *   2. Add /de/* routes to App.jsx
 *   3. Language switcher in Navbar will auto-activate
 */
export default function useTranslation() {
  const { pathname } = useLocation();
  const isGerman = pathname.startsWith("/de");
  return (isGerman && de) ? de : en;
}

/**
 * getTranslation(pathname)
 * Non-hook version for use outside React components.
 */
export function getTranslation(pathname = "") {
  const isGerman = pathname.startsWith("/de");
  return (isGerman && de) ? de : en;
}

export { en };
